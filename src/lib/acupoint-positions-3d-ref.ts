// ═══════════════════════════════════════
// 坐标转换函数：外部坐标系 → 知音坐标系
// 外部：Y(-1.5~1.5), X(-0.4~0.4), Z(-0.28~0.32)
// 知音：Y(0~1.714), X(-0.557~0.557), Z(-0.099~0.368)
// ═══════════════════════════════════════

export function convertToZhiyinCoord(extPos: AcupointPosition3DRef): [number, number, number] {
  // Y: 线性映射 (-1.5~1.5) → (0~1.714)
  const newY = (extPos.y + 1.5) / 3.0 * 1.714;
  // X: 线性映射 (-0.4~0.4) → (-0.557~0.557)
  const newX = (extPos.x + 0.4) / 0.8 * 1.114 - 0.557;
  // Z: 线性映射 (-0.28~0.32) → (-0.099~0.368)
  const newZ = (extPos.z + 0.28) / 0.6 * 0.467 - 0.099;
  return [Number(newX.toFixed(6)), Number(newY.toFixed(6)), Number(newZ.toFixed(6))];
}

// 按code获取转换后的坐标
export function getConvertedPosition(code: string): [number, number, number] | undefined {
  const ref = ACUPOINT_POSITIONS_REF[code];
  if (!ref) return undefined;
  return convertToZhiyinCoord(ref);
}

