export type TcmElement = 'wood' | 'fire' | 'earth' | 'metal' | 'water';

/** 知识章节内容区段 */
export interface TcmSection {
  heading?: string;
  text?: string;
  list?: string[];
  cards?: { icon: string; name: string; desc: string }[];
  table?: { headers: string[]; rows: string[][] };
}

/** 知识章节 */
export interface TcmChapter {
  id: string;
  name: string;
  icon: string;
  zone: string;
  xpReward: number;
  element: TcmElement;
  content: {
    title: string;
    subtitle: string;
    category: string;
    sections: TcmSection[];
    highlight: { icon: string; text: string };
  };
  quiz: TcmQuizQuestion[];
}

/** 测验题目 */
export interface TcmQuizQuestion {
  q: string;
  opts: string[];
  ans: number;
  explain: string;
}

/** 修炼殿堂 */
export interface TcmZone {
  id: string;
  name: string;
  icon: string;
  element: TcmElement;
  levelRequired: number;
  desc: string;
  chapters: string[]; // chapter ids
}

/** 等级体系 */
export interface TcmLevel {
  lv: number;
  title: string;
  xpRequired: number;
  reward: string;
}

/** Boss数据 */
export interface TcmBoss {
  id: string;
  name: string;
  icon: string;
  zone: string;
  hp: number;
  element: TcmElement;
  levelRequired: number;
  desc: string;
  questions: TcmQuizQuestion[];
  reward: { xp: number; gems: number; achievement?: string };
}

/** 成就数据 */
export interface TcmAchievement {
  id: string;
  name: string;
  icon: string;
  desc: string;
  condition: string;
  tier: 'bronze' | 'silver' | 'gold' | 'platinum';
}

/** 每日一识 */
export interface TcmTip {
  h: string;
  p: string;
}

